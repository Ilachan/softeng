/**
 * @section Authentication and Authorization Utilities
 * The following section contains helper functions designed to enforce
 * strict role-based access control (RBAC). In this specific context,
 * we are targeting the 'Instructor' role, identified by the internal
 * ID of 4.
 */

// requireInstructorRole is a middleware-like helper function that performs
// multi-stage verification on the incoming request context.
//
// 1. Extraction: It attempts to pull the JWT string from the Authorization header.
// 2. Role Validation: It decrypts the token to verify if the roleID matches '4'.
// 3. Identity Verification: It extracts the unique UserID associated with the token.
//
// This ensures that only authorized instructors can access the sensitive
// administrative endpoints defined in this package.
//
// @param c *gin.Context - The Gin framework context containing the request data.
// @returns (uint) - The verified UserID of the instructor.
// @returns (error) - Returns nil on success, or a specific error if validation fails.
func requireInstructorRole(c *gin.Context) (uint, error) {
	/*
	 * Step 1: Token Retrieval
	 * We rely on a helper function 'getTokenStringFromAuthHeader' to parse
	 * the Bearer token. If the header is missing or malformed, we terminate early.
	 */
	tokenString, err := getTokenStringFromAuthHeader(c)
	if err != nil {
		// Respond with 401 Unauthorized if the token is completely missing
		c.JSON(http.StatusUnauthorized, gin.H{"error": err.Error()})
		return 0, err
	}

	/*
	 * Step 2: Role Identification
	 * The service layer validates the token's integrity and signature.
	 * We then check if the user is explicitly assigned to roleID 4 (Instructor).
	 */
	roleID, err := service.GetRoleIDFromToken(tokenString)
	if err != nil {
		// Handle expired signatures or tampered tokens
		c.JSON(http.StatusUnauthorized, gin.H{"error": "invalid or expired token"})
		return 0, err
	}

	/*
	 * Step 3: Authorization Check
	 * If the user is authenticated but does not have sufficient privileges,
	 * we return 403 Forbidden. This prevents students or guests from
	 * accessing instructor-only data.
	 */
	if roleID != 4 {
		c.JSON(http.StatusForbidden, gin.H{"error": "Forbidden: instructor role required"})
		return 0, errors.New("forbidden")
	}

	/*
	 * Step 4: Subject Extraction
	 * Finally, we extract the primary key (UserID) from the token claims.
	 * This ID is used to filter database queries so instructors only see
	 * their own managed courses.
	 */
	userID, err := service.ExtractUserIDFromToken(tokenString)
	if err != nil {
		c.JSON(http.StatusUnauthorized, gin.H{"error": "invalid or expired token"})
		return 0, err
	}

	return userID, nil
}

/**
 * @section Course Management Handlers
 * This section contains controllers that allow instructors to view and
 * manage their course listings and student rosters.
 */

// InstructorListCourses handles the GET request to retrieve all courses
// assigned to the authenticated instructor.
//
// Logic Flow:
// - Call requireInstructorRole to verify the user.
// - Invoke service.ListInstructorCourses using the extracted ID.
// - Map the results to a JSON response.
func InstructorListCourses(c *gin.Context) {
	/* * Authenticate the instructor before proceeding to data retrieval.
	 * Error handling is managed inside requireInstructorRole.
	 */
	instructorID, err := requireInstructorRole(c)
	if err != nil {
		return
	}

	/* * Fetch course data from the persistence layer via the service package.
	 * This typically performs a JOIN between courses and the instructor link table.
	 */
	courses, err := service.ListInstructorCourses(instructorID)
	if err != nil {
		// Internal server errors suggest database connectivity issues or logic bugs
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	// Success: Return the list of course objects with a 200 OK status
	c.JSON(http.StatusOK, gin.H{"courses": courses})
}

// InstructorListCourseEnrollments fetches the list of students (and their status)
// for a specific course, provided the course belongs to the requesting instructor.
//
// Route: GET /instructor/courses/:id/enrollments
func InstructorListCourseEnrollments(c *gin.Context) {
	/* Ensure the caller is an instructor */
	instructorID, err := requireInstructorRole(c)
	if err != nil {
		return
	}

	/* * Path Parameter Parsing:
	 * The course ID is passed as a string in the URL. We must parse it to uint32/uint.
	 */
	courseIDStr := c.Param("id")
	courseID64, err := strconv.ParseUint(courseIDStr, 10, 32)
	if err != nil {
		// Invalid non-numeric ID triggers a 400 Bad Request
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid class ID"})
		return
	}

	/* * Data Fetching:
	 * The service layer checks ownership: does this courseID actually belong
	 * to this instructorID?
	 */
	enrollments, err := service.ListInstructorCourseEnrollments(instructorID, uint(courseID64))
	if err != nil {
		// Logic-specific error handling based on service layer feedback
		if err.Error() == "forbidden" {
			// Scenario: The instructor is valid, but doesn't own this specific course
			c.JSON(http.StatusForbidden, gin.H{"error": "forbidden"})
			return
		}
		if err.Error() == "class not found" {
			// Scenario: The course ID does not exist in the database
			c.JSON(http.StatusNotFound, gin.H{"error": "class not found"})
			return
		}
		// Generic fallback for unexpected errors
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	/* Send back the enrollment roster */
	c.JSON(http.StatusOK, gin.H{"enrollments": enrollments})
}

/**
 * @section Enrollment Modification
 * Structures and functions in this section deal with adding or
 * modifying student enrollment records.
 */

// InstructorAddEnrollmentInput defines the JSON body required to
// manually enroll a student into a course.
type InstructorAddEnrollmentInput struct {
	// UserID is the unique identifier of the student to be added
	UserID uint `json:"user_id" binding:"required"`
}

// InstructorAddEnrollment allows an instructor to manually add a student
// to a course session. It handles validation for seat availability and
// session timing.
func InstructorAddEnrollment(c *gin.Context) {
	/* Auth Check */
	instructorID, err := requireInstructorRole(c)
	if err != nil {
		return
	}

	/* Parameter Extraction */
	courseIDStr := c.Param("id")
	courseID64, err := strconv.ParseUint(courseIDStr, 10, 32)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid class ID"})
		return
	}

	/* JSON Body Binding */
	var input InstructorAddEnrollmentInput
	if err := c.ShouldBindJSON(&input); err != nil {
		// Validation failed: e.g., user_id field is missing or wrong type
		c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
		return
	}

	/* Execute Business Logic */
	if err := service.InstructorAddEnrollment(instructorID, input.UserID, uint(courseID64)); err != nil {
		/* * Comprehensive Error Mapping:
		 * Maps business logic failures to appropriate HTTP status codes.
		 */
		switch err.Error() {
		case "forbidden":
			// Access denied to this specific course resource
			c.JSON(http.StatusForbidden, gin.H{"error": "forbidden"})
		case "user not found", "class not found", "no upcoming session found for this class":
			// Resource discovery failures
			c.JSON(http.StatusNotFound, gin.H{"error": err.Error()})
		case "enrollment already exists", "class is full":
			// Logical conflicts (e.g., duplicate entry or capacity reached)
			c.JSON(http.StatusConflict, gin.H{"error": err.Error()})
		default:
			// Catch-all for database or system errors
			c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		}
		return
	}

	// 201 Created: Success message indicating the student is now enrolled
	c.JSON(http.StatusCreated, gin.H{"message": "user enrolled successfully"})
}

// InstructorUpdateStatusInput defines the expected payload for updating
// the status of an enrollment (e.g., from 'pending' to 'completed').
type InstructorUpdateStatusInput struct {
	// UserID of the student whose status is changing
	UserID uint `json:"user_id" binding:"required"`
	// Status string (e.g., "active", "dropped", "completed")
	Status string `json:"status" binding:"required"`
}

// InstructorUpdateEnrollmentStatus allows an instructor to update the
// state of a student's participation in a course.
func InstructorUpdateEnrollmentStatus(c *gin.Context) {
	/* Identity Check */
	instructorID, err := requireInstructorRole(c)
	if err != nil {
		return
	}

	/* Path variable parsing */
	courseIDStr := c.Param("id")
	courseID64, err := strconv.ParseUint(courseIDStr, 10, 32)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid class ID"})
		return
	}

	/* Input validation */
	var input InstructorUpdateStatusInput
	if err := c.ShouldBindJSON(&input); err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
		return
	}

	/* Perform Update */
	if err := service.UpdateEnrollmentStatusByInstructor(instructorID, uint(courseID64), input.UserID, input.Status); err != nil {
		// Specific error branches for fine-grained client feedback
		if err.Error() == "forbidden" {
			c.JSON(http.StatusForbidden, gin.H{"error": "forbidden"})
			return
		}
		if err.Error() == "enrollment not found" {
			c.JSON(http.StatusNotFound, gin.H{"error": "enrollment not found"})
			return
		}
		// Default to 400 for generic input-related service errors
		c.JSON(http.StatusBadRequest, gin.H{"error": err.Error()})
		return
	}

	// Confirmation response
	c.JSON(http.StatusOK, gin.H{"message": "status updated"})
}

