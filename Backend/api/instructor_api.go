// InstructorDeleteUserEnrollment handles the removal of a student from a course.
// This is typically used for course drops or corrections.
//
// Route: DELETE /instructor/courses/:id/enrollments/:user_id
func InstructorDeleteUserEnrollment(c *gin.Context) {
	/* Guard clause for Instructor role */
	_, err := requireInstructorRole(c)
	if err != nil {
		return
	}

	/* Parse dual path parameters: course ID and target user ID */
	courseIDStr := c.Param("id")
	userIDStr := c.Param("user_id")

	courseID, err := strconv.ParseUint(courseIDStr, 10, 32)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid course ID"})
		return
	}
	userID, err := strconv.ParseUint(userIDStr, 10, 32)
	if err != nil {
		c.JSON(http.StatusBadRequest, gin.H{"error": "Invalid user ID"})
		return
	}

	/* Execution: Remove the record from the database */
	if err := service.InstructorDeleteUserEnrollment(uint(userID), uint(courseID)); err != nil {
		// If deletion fails (e.g., DB constraint or connection error)
		c.JSON(http.StatusInternalServerError, gin.H{"error": err.Error()})
		return
	}

	// Success 200 OK
	c.JSON(http.StatusOK, gin.H{"message": "enrollment deleted"})
}

